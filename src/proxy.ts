import { type NextRequest } from "next/server";
import { updateSession } from "@/supabase-clients/middleware";

/**
 * Global Next.js proxy for Supabase SSR session refresh and authentication gate.
 * Follows Next.js 16 proxy convention.
 */
export async function proxy(request: NextRequest) {
  return await updateSession(request);
}

export const config = {
  matcher: [
    /*
     * Match all request paths except for the ones starting with:
     * - _next/static (static files)
     * - _next/image (image optimization files)
     * - favicon.ico (favicon file)
     * - images/static files (.svg, .png, .jpg, .jpeg, .gif, .webp)
     */
    "/((?!_next/static|_next/image|favicon.ico|.*\\.(?:svg|png|jpg|jpeg|gif|webp)$).*)",
  ],
};
